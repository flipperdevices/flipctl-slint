/// The art for a kind, as `ident` and the taxonomy table name kinds; unknown otherwise.
fn art(kind: Option<&str>) -> &'static [&'static str; 14] {
    match kind.unwrap_or("") {
        "Phone" => &PHONE,
        "Tablet" => &TABLET,
        "Laptop" => &LAPTOP,
        "Computer" | "Server" | "Storage" => &COMPUTER,
        "TV" | "Projector" | "Monitor" | "Display" => &TV,
        "Media Player" | "Set-top Box" => &MEDIA,
        "Printer" | "Scanner" => &PRINTER,
        "Speaker" | "Headphones" | "Audio" => &SPEAKER,
        "Game Console" | "Handheld Console" => &CONSOLE,
        "Camera" => &CAMERA,
        "IoT" => &IOT,
        "Watch" => &WATCH,
        "Router" | "Access Point" => &ROUTER,
        _ => &UNKNOWN,
    }
}

thread_local! {
    static MADE: std::cell::RefCell<HashMap<usize, slint::Image>> = Default::default();
}

/// Whether a kind has an icon of its own.
#[cfg(test)]
pub fn known(kind: &str) -> bool {
    !std::ptr::eq(art(Some(kind)), &UNKNOWN)
}

/// The icon for a kind, made once per art.
pub fn for_kind(kind: Option<&str>) -> slint::Image {
    let rows = art(kind);
    MADE.with(|m| {
        m.borrow_mut().entry(rows.as_ptr() as usize).or_insert_with(|| icon(rows)).clone()
    })
}
