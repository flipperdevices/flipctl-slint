#!/usr/bin/env python3
"""Turn wifi_taxonomy's signature database into the Wi-Fi Scanner's lookup table.

    tools/wifi-taxonomy-to-rust.py WIFI_TAXONOMY_CHECKOUT > apps/wifi-scanner/src/taxonomy.rs

The database (github.com/NetworkDeviceTaxonomy/wifi_taxonomy, taxonomy/wifi.py, Apache-2.0)
keys each device by its probe and association request signatures together. The app
rarely sees both from one MAC, so each half is kept on its own, and only where it names
a single device and has HT capabilities to tell it by. Halves are stored as their FNV-1a
64 hash, which the app computes the same way. The data is read as text, never imported
or run.
"""

import re
import subprocess
import sys

# Kinds, as the app names them, by device name; first match wins, the rest are phones
KINDS = [
    (r" or Tab ", "Phone"),
    (r"Watch", "Watch"),
    (r"Fire TV|Chromecast|Roku|Apple TV|TiVo|DirecTV|Dish Network|Slingbox|Nexus Player|SHIELD", "Media Player"),
    (r"TV", "TV"),
    (r"Xbox|Playstation|Wii", "Game Console"),
    (r"Printer", "Printer"),
    (r"Echo|Google Home|Speaker", "Speaker"),
    (r"Dropcam|Nest Cam", "Camera"),
    (r"Dash Button|WeMo|thermostat|Thermostat|Nest Protect|LIFX|smart bulb|smart plug|Wink Hub|Withings", "IoT"),
    (r"Aruba AP|U-verse|Google Fiber|OnHub|Google Wifi|NetGEAR|Technicolor", "Router"),
    (r"iPad|Nexus 7|Nexus 9|Nexus 10|Tab|Kindle|Nook|Xoom|Tablet|LG Pad|Tango", "Tablet"),
    (r"Chromebook|Surface", "Laptop"),
]


def kind(name):
    for pattern, k in KINDS:
        if re.search(pattern, name):
            return k
    return "Phone"


def fnv64(text):
    h = 0xCBF29CE484222325
    for b in text.encode():
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    checkout = sys.argv[1]
    commit = subprocess.run(
        ["git", "-C", checkout, "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    src = open(f"{checkout}/taxonomy/wifi.py", encoding="utf-8").read()
    entries = re.findall(r"'(wifi4\|[^']+)':\s*\(\s*'([^']*)', '([^']*)', '([^']*)'\)", src)
    halves = {"probe": {}, "assoc": {}}
    for sig, genus, _species, _band in entries:
        for part in sig.split("|"):
            for half, seen in halves.items():
                if part.startswith(half + ":"):
                    seen.setdefault(part, set()).add(genus)
    names = sorted({g for _, g, _, _ in entries})
    index = {n: i for i, n in enumerate(names)}

    out = sys.stdout
    out.write(
        "// Generated by tools/wifi-taxonomy-to-rust.py from wifi_taxonomy\n"
        f"// ({commit}), taxonomy/wifi.py: Copyright 2015 Google Inc.,\n"
        "// Apache-2.0. Changed: reduced to request signature hashes and device names. Do not edit.\n"
        "\n"
        "//! Devices by the signature of their probe or association request, from wifi_taxonomy.\n"
        "//! Each half is kept only where it names one device and has HT capabilities.\n"
        "\n"
        "/// Device names and the kind each is.\n"
        "pub const NAMES: &[(&str, &str)] = &[\n"
    )
    for n in names:
        out.write(f'    ("{n}", "{kind(n)}"),\n')
    out.write("];\n")
    for half, seen in halves.items():
        # A signature without HT capabilities is too plain to tell devices apart
        rows = sorted(
            (fnv64(sig), index[next(iter(g))]) for sig, g in seen.items() if len(g) == 1 and ",htcap:" in sig
        )
        out.write(f"\n/// {half.capitalize()} request signature hashes, sorted, and the name each gives.\n")
        out.write(f"pub const {half.upper()}: &[(u64, u16)] = &[\n")
        for h, i in rows:
            out.write(f"    (0x{h:016x}, {i}),\n")
        out.write("];\n")


main()
