/// The compiled .slint components.
///
/// Generated by slint-build from `ui/`, re-exported here so binaries do not each
/// have to run the compiler. Behind `screens`, because this is Root and every
/// screen with it: a consumer that needs one screen compiles its own entry file
/// against `ui/` instead and takes only `slint`.
#[cfg(feature = "screens")]
pub mod ui {
    slint::include_modules!();
}

/// Design tokens, generated from tokens.toml at build time.
#[allow(dead_code)]
pub mod theme {
    include!(concat!(env!("OUT_DIR"), "/theme.rs"));
}

