#!/usr/bin/env python3
"""Rasterise a flipctl-fonts TTF into a Rust glyph table, for a font the prototype has no
table of.

The same rasterisation fake-flipctl2's ttf-to-js.py does: draw each glyph at the panel's
16px, threshold at half, crop to its first inked column, advance from the font's metrics.
A pixel font at the size it was drawn for has no partial coverage, so the threshold keeps
every pixel; the output is checked against a design render of the font, not trusted.

Usage: ttf-font-to-rust.py <font.ttf> <RustName> <rows> > out.rs
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126
SIZE, COLS = 16, 16

path, name, rows = sys.argv[1], sys.argv[2], int(sys.argv[3])
font = ImageFont.truetype(path, SIZE)
glyphs = []
for code in range(FIRST, LAST + 1):
    ch = chr(code)
    img = Image.new("L", (40, rows + 4), 0)
    ImageDraw.Draw(img).text((1, 0), ch, fill=255, font=font)
    px = img.load()
    bits = [[px[x, y] >= 128 for x in range(40)] for y in range(rows + 4)]
    if any(any(r) for r in bits[rows:]):
        raise SystemExit(f"{path}: {ch!r} reaches below {rows} rows")
    inked = [x for x in range(40) if any(bits[y][x] for y in range(rows))]
    left = inked[0] if inked else 1
    if inked and inked[-1] - left >= COLS:
        raise SystemExit(f"{path}: {ch!r} is wider than {COLS} columns")
    advance = max(int(round(font.getlength(ch))), 1)
    packed = [sum(1 << (COLS - 1 - c) for c in range(COLS) if left + c < 40 and bits[r][left + c])
              for r in range(rows)]
    glyphs.append((advance, packed if code != 32 else [0] * rows))

const = f"{name}_GLYPHS"
print(f"// @generated by tools/ttf-font-to-rust.py from {path.rsplit('/', 1)[-1]}. Do not edit.")
print()
print(f"/// {name.title()}: {rows} rows of {COLS} bits, MSB is the leftmost pixel.")
print(f"pub const {name}: BitmapFont = BitmapFont {{")
print(f"    rows: {rows},\n    cols: {COLS},\n    first: {FIRST},\n    glyphs: &{const},\n}};")
print()
print("#[rustfmt::skip]")
print(f"const {const}: [Glyph; {LAST - FIRST + 1}] = [")
for code, (advance, packed) in zip(range(FIRST, LAST + 1), glyphs):
    rows_s = ", ".join(f"0x{v:04x}" for v in packed)
    print(f"    Glyph {{ advance: {advance}, rows: &[{rows_s}] }},")
print("];")
